"""Score raw outputs in results/raw and write tables and the robustness plot.

  uv run python scripts/report.py
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

from wxeval.eval.metrics import evaluate
from wxeval.report import (
    LAYOUT,
    load_prepare,
    paired_tests,
    per_field_table,
    score_freshness,
    score_runs,
    summarize,
    variant_table,
    write_csv,
)
from wxeval.schemas import SCHEMAS
from wxeval.sites.variants import VARIANTS

ROOT = Path(__file__).resolve().parent.parent


def sanity(build: Path) -> str:
    """Metric checks on ground truth itself: perfect, shuffled values, empty output."""
    rows = {"perfect": [], "shuffled": [], "empty": []}
    rng = random.Random(0)
    for path in sorted((build / "truth").glob("*/*/s[1-9]*.json")):
        t = json.loads(path.read_text())
        schema = SCHEMAS[t["kind"]]
        gold = t["records"]
        shuffled = [dict(r) for r in gold]
        for name in schema.names():
            col = [r[name] for r in shuffled]
            rng.shuffle(col)
            for r, v in zip(shuffled, col, strict=True):
                r[name] = v
        for label, pred in (("perfect", gold), ("shuffled", shuffled), ("empty", [])):
            rows[label].append(evaluate(pred, gold, schema, t["key"], t["twins"],
                                        t["page_of"]).fields.f1)
    lines = ["| Check | Mean field F1 | Instances |", "|---|---|---|"]
    for label, vals in rows.items():
        lines.append(f"| {label} | {sum(vals) / len(vals):.3f} | {len(vals)} |")
    return "\n".join(lines) + "\n"


def plot(grid: dict[str, dict[str, float]], out: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    order = [v for v in ["base", "hashed_classes", "deep_wrap", "layout_b", "redesign"]
             if any(v in g for g in grid.values())]
    fig, ax = plt.subplots(figsize=(7, 4))
    for system, vals in sorted(grid.items()):
        ax.plot(order, [vals.get(v, float("nan")) for v in order], marker="o", label=system)
    ax.set_ylabel("Field F1")
    ax.set_ylim(-0.02, 1.02)
    ax.set_title("Field F1 as the page layout changes (mean over sites and seeds)")
    ax.grid(alpha=0.3)
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(out, dpi=150)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=str(ROOT / "results"))
    ap.add_argument("--fetch", default="browser", choices=["browser", "http"])
    args = ap.parse_args()
    results = Path(args.results)
    build = ROOT / "build"
    raw = results / "raw" / args.fetch
    rows = score_runs(raw, build)
    fresh = score_freshness(raw, build)
    write_csv(results / "runs.csv", rows)
    write_csv(results / "freshness.csv", fresh)
    main_md, extra_md = summarize(rows, fresh, load_prepare(raw))
    var_md, grid = variant_table(rows)
    shop_md, _ = variant_table(rows, "shop")
    jobs_md, _ = variant_table(rows, "jobs")
    pairs = [("llm_page", "llm_code"), ("llm_page", "handwritten"),
             ("crawl4ai_llm", "crawl4ai_schema"), ("llm_page", "crawl4ai_llm"),
             ("llm_page", "scrapegraph")]
    sections = [
        "# Results\n\nGenerated by scripts/report.py from results/raw. Do not edit by hand.\n"
        f"Fetch mode: {args.fetch}. Intervals are 95% bootstrap intervals over (site, seed) "
        "clusters.\n",
        "## Main table\n", main_md,
        "## Other metrics\n", extra_md,
        "## Field F1 by variant, both sites\n", var_md,
        "## Field F1 by variant, shop\n", shop_md,
        "## Field F1 by variant, jobs\n", jobs_md,
        "## Field F1 per field on the base variant\n", per_field_table(raw, build),
        "## Paired comparisons on the four layout variants\n",
        paired_tests(rows, pairs, LAYOUT),
        "## Metric sanity checks\n", sanity(build),
    ]
    errors = [r for r in rows if r["error"]]
    if errors:
        sections.append(f"## Runs with errors\n\n{len(errors)} of {len(rows)} runs raised an "
                        "error and count as empty output. See runs.csv.\n")
    (results / "tables.md").write_text("\n".join(sections))
    if any(v in VARIANTS for g in grid.values() for v in g):
        plot(grid, results / "robustness.png")
    page_errors = sum(r["page_errors"] for r in rows)
    if page_errors:
        with (results / "tables.md").open("a") as fh:
            fh.write(f"\n{page_errors} pages failed inside otherwise finished runs. "
                     "See page_errors in runs.csv.\n")
    print((results / "tables.md").read_text())


if __name__ == "__main__":
    main()
